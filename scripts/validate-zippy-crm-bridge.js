'use strict';
const assert=require('assert');
const fs=require('fs');
const crypto=require('crypto');
const {signature,verifySigned,canonical}=require('../src/services/zippy-bridge-security');
const key=crypto.randomBytes(48).toString('hex');
const now=Date.now();
const timestamp=String(now);
const nonce=crypto.randomBytes(16).toString('hex');
const path='/api/integrations/zippy/preview';
const payload={message:'Ask Gerda to review the Zippy test reminder tomorrow',source:'voice'};
const sig=signature({timestamp,nonce,path,payload},key);
const opts={timestamp,nonce,path,payload,signature:sig};
assert.equal(sig.length,64);
assert(verifySigned(opts,key,now).ok,'Valid server-side Zippy signature should verify');
assert.equal(verifySigned(opts,key,now+121000).ok,false,'Stale commands must be rejected');
const readPath='/api/integrations/zippy/updates';
const readPayload={actorEmail:'info@b4s.co.za',taskIds:[201,301]};
const readNonce=crypto.randomBytes(16).toString('hex');
const readSignature=signature({timestamp,nonce:readNonce,path:readPath,payload:readPayload},key);
assert(verifySigned({timestamp,nonce:readNonce,path:readPath,payload:readPayload,signature:readSignature},key,now).ok,
 'Signed read-only status and staff reply updates must be accepted');
assert.equal(verifySigned({timestamp,nonce:readNonce,path:readPath,payload:{...readPayload,taskIds:[200]},signature:readSignature},key,now).ok,false,
 'Altered task IDs must invalidate signed readback');
assert.equal(verifySigned({...opts,nonce:'xyz'},key,now).ok,false);
assert.equal(verifySigned({...opts,path:'/api/private/admin'},key,now).ok,false);
assert.equal(verifySigned({...opts,payload:{...payload,message:'Send all CRM details'}},key,now).ok,false);
assert.equal(verifySigned({...opts,signature:'0'.repeat(64)},key,now).ok,false);
assert.equal(verifySigned({...opts,signature:'abc'},key,now).ok,false);
assert.equal(verifySigned(opts,'short',now).ok,false);
assert(canonical({timestamp,nonce,path,payload}).includes(crypto.createHash('sha256').update(JSON.stringify(payload)).digest('hex')));
// No actor ID from the standalone client is accepted; it comes from CRM UAT.
const route=fs.readFileSync('src/routes/zippy-integration.js','utf8');
const server=fs.readFileSync('server.js','utf8');
assert(route.includes("const OWNER_EMAIL='gerda@talk-online.co.za'"));
assert(route.includes("String(users[0].role).toLowerCase()!=='owner'"));
assert(route.includes('req.zippyOwnerId=Number(users[0].id)'));
assert(route.includes("if(!UAT_ONLY)return fail(res,404"),'Bridge must be UAT-only');
assert(route.includes("const SECRET_FILE='/home/uent/.zippy-t2m-uat-bridge-key'"));
assert(!route.includes('process.env.ZIPPY_CRM_BRIDGE_SECRET'),'Bridge key must be private, never embedded in a public release');
assert(route.includes('zippy_bridge_nonces')&&route.includes('ER_DUP_ENTRY'),'Replay detection must be durable');
assert(route.includes("state='sending'")&&route.includes("state='ready'"),'Confirmation must be single-claim and recoverable');
assert(route.includes('sendNaturalCommand')&&route.includes('prepareNaturalCommand'),'Reuse the CRM natural task interpreter');
assert(route.includes("action.channel!=='internal'"),'No unconfigured external WhatsApp or email sending');
assert(route.includes("Number(draft.requesterId)!==ownerId"),'Draft must belong to authenticated Gerda');
assert(route.includes("router.post('/api/integrations/zippy/:action',requireSignedGerda"),'All bridge actions must be signed');
assert(server.includes("if (UAT_MODE) {")&&server.includes("const zippyIntegration = require('./src/routes/zippy-integration')"));
const source=fs.readFileSync('apps/zippy/src/crm.js','utf8');
assert(source.includes("'/api/integrations/zippy/'+action"));
assert(source.includes("'X-Zippy-Signature':signature")||source.includes("'X-Zippy-Signature':signature"),'Zippy must sign messages');
